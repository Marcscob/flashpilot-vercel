import { applyDeepDictOverlay } from "./app-ext-langs";

export type LedgerKind =
  | "welcome" | "flashcards" | "mindmap" | "note_format" | "chat" | "bulk"
  | "purchase" | "subscription" | "refund" | "gift" | "other";

export function ledgerKind(reason: string, actionId: string | null): LedgerKind {
  const a = actionId ?? "";
  if (reason === "welcome_kit" || a.startsWith("welcome:")) return "welcome";
  if (reason === "ai_flashcards" || a.startsWith("flashcards-save:")) return "flashcards";
  if (a.startsWith("ai-feature:")) {
    const cost = a.split(":")[1];
    if (cost === "mindmap" || cost === "note_format" || cost === "chat" || cost === "bulk") return cost;
    return "other";
  }
  if (reason === "purchase") return "purchase";
  if (reason === "subscription") return "subscription";
  if (reason === "refund") return "refund";
  if (reason === "gift" || reason === "bonus") return "gift";
  return "other";
}

