export function useBulkV2T(): BulkV2Copy {
  const { lang, extLang } = useLang();
  const od = useOverlayD();
  if (extLang) {
    const overlay = od ?? {};
    const formatCount = (key: string, fallback: string, n: number) =>
      (overlay[`bulkv2.${key}`] ?? fallback).replace(/\{n\}/g, String(n));
    return {
      ...applyDictOverlay(en, overlay, "bulkv2"),
      ...CAPTURE_GROUP_TRANSLATIONS[extLang],
      question: (n) => formatCount("question", BULK_V2_ENGLISH_SOURCE.question, n),
      createCards: (n) => formatCount("createCards", BULK_V2_ENGLISH_SOURCE.createCards, n),
      coinsNote: (n) => formatCount("coinsNote", BULK_V2_ENGLISH_SOURCE.coinsNote, n),
    };
  }
  return COPY[lang] ?? pt;
}
