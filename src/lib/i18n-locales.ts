/**
 * Camadas de tradução adicionais (i18n).
 * Cada idioma novo é um "overlay" aplicado sobre um dicionário base já existente:
 *  - pt-PT  → base pt (apenas as diferenças de Portugal)
 *  - fr/it/de → base en (o que não estiver traduzido cai no inglês)
 * Nada é removido: os dicionários pt, es e en originais continuam intactos.
 */

type AnyRecord = Record<string, unknown>;

function isPlainObject(v: unknown): v is AnyRecord {
  return typeof v === "object" && v !== null && !Array.isArray(v);
}

/** Mescla profundamente o overlay sobre a base, sem mutar nenhum dos dois. */
export function deepMergeDict<T>(base: T, overlay: unknown): T {
  if (!isPlainObject(base) || !isPlainObject(overlay)) return (overlay === undefined ? base : (overlay as T));
  const out: AnyRecord = { ...base };
  for (const [key, value] of Object.entries(overlay)) {
    const current = out[key];
    out[key] = isPlainObject(current) && isPlainObject(value) ? deepMergeDict(current, value) : value;
  }
  return out as T;
}

